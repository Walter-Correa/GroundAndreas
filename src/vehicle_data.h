inline bool GetVehicleModelDimensions(int modelId, float& sizeX, float& sizeY, float& sizeZ)
{
    if (modelId < 400 || modelId > 611)
    {
        sizeX = 2.0f;
        sizeY = 5.0f;
        sizeZ = 1.5f;
        return false;
    }
    const auto& dims = VEHICLE_MODEL_SIZES[modelId - 400];
    sizeX = dims.x;
    sizeY = dims.y;
    sizeZ = dims.z;
    return true;
}

inline float GetVehicleModelSizeZ(int modelId)
{
    if (modelId < 400 || modelId > 611)
    {
        return 1.5f;
    }
    return VEHICLE_MODEL_SIZES[modelId - 400].z;
}
